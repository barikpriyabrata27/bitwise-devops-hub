def main():
    questions = json.loads(QUESTION_FILE.read_text(encoding="utf-8"))
    existing_ids = {question["id"] for question in questions}
    next_id = max(existing_ids) + 1

    existing_scenario_questions = {
        question["question"] for question in questions if question.get("type") == "scenario"
    }

    added = []
    for category, difficulty, question_text, options, answer, explanation in SCENARIOS:
        if question_text in existing_scenario_questions:
            continue
        added.append(
            {
                "id": next_id,
                "category": category,
                "difficulty": difficulty,
                "type": "scenario",
                "question": question_text,
                "options": options,
                "answer": answer,
                "explanation": explanation,
            }
        )
        next_id += 1

    if not added:
        print("No new scenario questions to add; bank is already up to date.")
        return

    questions.extend(added)
    QUESTION_FILE.write_text(json.dumps(questions, indent=2) + "\n", encoding="utf-8")
    print(f"Added {len(added)} scenario questions. Bank now has {len(questions)} questions.")


if __name__ == "__main__":
    main()
